/// \file
/// Strong Gröbner basis computation over Z_{2^d}

#ifndef CPROVER_SOLVERS_ALGEBRAIC_GROEBNER_H
#define CPROVER_SOLVERS_ALGEBRAIC_GROEBNER_H

#include "poly_ring.h"

#include <cstddef>

/// Compute a strong Gröbner basis over Z_{2^d} and check for
/// unsatisfiability of a system of polynomial equations.
class strong_groebner_basist
{
public:
  /// \param max_steps: abort after this many reduction steps (0 = unlimited)
  explicit strong_groebner_basist(std::size_t max_steps = 10000)
    : max_steps{max_steps}
  {
  }

  enum class resultt
  {
    UNSAT,  // 1 is in the ideal (system has no solution)
    UNKNOWN // could not determine (basis computed but no constant found,
            // or step limit reached)
  };

  /// Compute strong Gröbner basis of the ideal generated by \p polys.
  /// Modifies \p polys in place to contain the basis.
  /// Returns UNSAT if a nonzero constant is found in the basis.
  resultt compute(std::vector<polynomialt> &polys);

  /// After compute() returns UNKNOWN, try to extract a candidate
  /// assignment. Looks for univariate linear polynomials in the basis.
  static std::map<std::size_t, mp_integer>
  extract_candidate(const std::vector<polynomialt> &basis, unsigned bw);

  /// Reduce a polynomial \p f by a (strong) Gr\"obner basis without
  /// any state mutation. Used by item 7's expression normalisation
  /// (see doc/paper-algebraic/expression-normalisation-design.md):
  /// after compute() has produced a basis, an arbitrary polynomial
  /// expression can be simplified by reducing it w.r.t.\ the basis,
  /// potentially yielding a constant or a shorter polynomial form
  /// that propagates algebraic insight to the bit-blast layer.
  ///
  /// \param f polynomial to reduce.
  /// \param basis the (strong) Gr\"obner basis to reduce against.
  /// \param max_steps step budget; reduction returns the partially
  ///   reduced polynomial if exceeded.
  /// \return the reduced polynomial $r$ such that $f \equiv r
  ///   \pmod{\langle \mathit{basis} \rangle}$.
  static polynomialt reduce_by_basis(
    const polynomialt &f,
    const std::vector<polynomialt> &basis,
    std::size_t max_steps = 10000);

  /// Set the bit-variable indices for Frobenius-aware idempotency
  /// reduction (Re 4 sub-goal 3).
  ///
  /// Bit variables satisfy b^2 = b in Z_{2^d}, so all higher
  /// powers reduce to b: b^k = b for k >= 1. When this set is
  /// non-empty, every polynomial constructed by s_polynomial(),
  /// strong_reduce(), or compute()'s 2-multiple step has its bit-
  /// variable exponents clamped to 1 immediately, avoiding the
  /// O(steps) cost of incrementally reducing high-degree
  /// bit-monomials via the b^2 - b basis elements.
  ///
  /// Sound because the clamping uses an identity already implied
  /// by the basis (idempotency); the result differs from the
  /// non-clamped polynomial only by elements of the
  /// (b^2 - b) ideal, all of which are zero in any model.
  void set_bit_vars(std::set<std::size_t> indices)
  {
    bit_vars = std::move(indices);
  }

  /// Set host substitutions for linear elimination (Re 4 sub-goal 3
  /// follow-on). Each entry maps a host variable index h to the
  /// polynomial expression that should replace h in every
  /// polynomial of the input basis. After substitution, the host
  /// is eliminated from the system; sum-decomposition equations
  /// (h = sum_i 2^i b_i) become trivial 0 = 0 and are dropped.
  ///
  /// Sound by construction: substitution replaces v with q in a
  /// polynomial system; the resulting variety is the projection
  /// of the original variety onto the v=q surface. The sum-
  /// decomposition constraint guarantees v = q in every model, so
  /// the projection preserves all original models.
  ///
  /// Applied at the start of compute(), before Frobenius
  /// reduction.
  void set_host_substitutions(std::map<std::size_t, polynomialt> subs)
  {
    host_substitutions = std::move(subs);
  }

private:
  std::size_t max_steps;
  std::size_t steps_taken = 0;
  std::set<std::size_t> bit_vars;
  std::map<std::size_t, polynomialt> host_substitutions;

  /// S-polynomial of f and g
  polynomialt s_polynomial(const polynomialt &f, const polynomialt &g);

  /// Strong reduction of f by the basis.
  /// Returns the remainder after dividing f by all elements of basis.
  polynomialt
  strong_reduce(const polynomialt &f, const std::vector<polynomialt> &basis);

  /// Check if any element of the basis is a nonzero constant
  bool has_constant(const std::vector<polynomialt> &basis) const;
};

#endif // CPROVER_SOLVERS_ALGEBRAIC_GROEBNER_H
