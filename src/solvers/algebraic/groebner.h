/// \file
/// Strong Gröbner basis computation over Z_{2^d}

#ifndef CPROVER_SOLVERS_ALGEBRAIC_GROEBNER_H
#define CPROVER_SOLVERS_ALGEBRAIC_GROEBNER_H

#include "poly_ring.h"

#include <cstddef>

/// Compute a strong Gröbner basis over Z_{2^d} and check for
/// unsatisfiability of a system of polynomial equations.
class strong_groebner_basist
{
public:
  /// \param max_steps: abort after this many reduction steps (0 = unlimited)
  explicit strong_groebner_basist(std::size_t max_steps = 10000)
    : max_steps{max_steps}
  {
  }

  enum class resultt
  {
    UNSAT,  // 1 is in the ideal (system has no solution)
    UNKNOWN // could not determine (basis computed but no constant found,
            // or step limit reached)
  };

  /// Compute strong Gröbner basis of the ideal generated by \p polys.
  /// Modifies \p polys in place to contain the basis.
  /// Returns UNSAT if a nonzero constant is found in the basis.
  resultt compute(std::vector<polynomialt> &polys);

  /// After compute() returns UNKNOWN, try to extract a candidate
  /// assignment. Looks for univariate linear polynomials in the basis.
  static std::map<std::size_t, mp_integer>
  extract_candidate(const std::vector<polynomialt> &basis, unsigned bw);

private:
  std::size_t max_steps;
  std::size_t steps_taken = 0;

  /// S-polynomial of f and g
  polynomialt s_polynomial(const polynomialt &f, const polynomialt &g);

  /// Strong reduction of f by the basis.
  /// Returns the remainder after dividing f by all elements of basis.
  polynomialt
  strong_reduce(const polynomialt &f, const std::vector<polynomialt> &basis);

  /// Check if any element of the basis is a nonzero constant
  bool has_constant(const std::vector<polynomialt> &basis) const;
};

#endif // CPROVER_SOLVERS_ALGEBRAIC_GROEBNER_H
