// The unary type-trait built-ins of GCC and Clang (used by libc++ and
// libstdc++ for <type_traits>), checked against clang 18 for scalar,
// compound and class types.  Fixed: enumerations were integral and
// arithmetic; pointers to members and std::nullptr_t were pointers and
// std::nullptr_t compound; references were standard-layout and POD; void,
// function types, arrays of unknown bound and classes with deleted or
// inaccessible destructors were destructible; defaulted special members
// made a class non-trivial; a reference member made it not trivially
// copyable; a class with data members in a base and in itself was
// standard-layout; constructors were not checked for constexpr in
// __is_literal_type; __has_unique_object_representations,
// __is_trivially_relocatable and the GCC __has_trivial_* / __has_nothrow_*
